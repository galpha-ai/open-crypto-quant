/// Configuration for paper trading fill simulation.
///
/// This struct groups fill simulation options that control how the
/// `PaperTradingOrderExecutor` simulates order fills against live market data.
#[derive(Debug, Clone)]
pub struct PaperTradingConfig {
    /// If true, sell orders require positive inventory to fill.
    /// This prevents "naked shorting" which is not realistic for venues like Polymarket.
    /// Default: true
    pub enforce_inventory_constraints: bool,
    /// Latency simulation for realistic fill modeling.
    /// When set, orders are not eligible for fills until after a simulated placement latency.
    /// Default: None (immediate eligibility)
    pub latency_config: Option<LatencySimulationConfig>,
}

impl Default for PaperTradingConfig {
    fn default() -> Self {
        Self {
            enforce_inventory_constraints: true,
            latency_config: None,
        }
    }
}
