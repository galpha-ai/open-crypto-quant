    /// Execute a limit order by adding it to the pending orders map.
    ///
    /// For ImmediateOrCancel (IOC) orders, this implementation does not attempt
    /// immediate fill checking - it simply places the order and relies on
    /// subsequent trade events to trigger fills.
    #[instrument(skip(self))]
    async fn execute_limit_order(&self, order: Order) -> Result<LimitOrderEvent> {
        let (size, limit_price, side, time_in_force) = match &order.order_type {
            OrderType::LimitBuy {
                quote_amount,
                limit_price,
                time_in_force,
            } => {
                // Convert quote_amount to base units (token amount) for consistent tracking.
                // Intent signals express size in base units, so reconciliation comparisons
                // need the same unit to avoid spurious cancel/replace cycles.
                let base_size = *quote_amount / *limit_price;
                (base_size, *limit_price, OrderSide::Buy, *time_in_force)
            }
            OrderType::LimitSell {
                token_amount,
                limit_price,
                time_in_force,
                ..
            } => (*token_amount, *limit_price, OrderSide::Sell, *time_in_force),
            _ => {
                return Err(anyhow!(
                    "execute_limit_order called with non-limit order type: {:?}",
                    order.order_type
                ));
            }
        };

        let order_id = self.generate_order_id();

        // Compute when this order becomes eligible for fills (latency simulation)
        let eligible_for_fills_at = self.compute_eligibility_time(order.timestamp);
        let deferred_lifecycle = self.config.latency_config.is_some();

        // Create pending order
        let pending = PendingPaperOrder {
            order_id: order_id.clone(),
            mint: order.mint.clone(),
            market: order.market.clone(),
            side,
            price: limit_price,
            original_size: size,
            remaining_size: size,
            placed_at: order.timestamp,
            time_in_force,
            signal_id: order.signal_id.clone(),
            exit_mode: order.exit_mode,
            context: order.context.clone(),
            eligible_for_fills_at,
            cancel_confirm_at: None,
        };

        self.lifecycle_record_place_request(&order_id, &pending)?;
        if !deferred_lifecycle {
            let lifecycle_state = self.lifecycle_record_place_success(&order_id)?;
            if !matches!(lifecycle_state, LifecycleState::Open) {
                return Err(anyhow!(
                    "unexpected lifecycle state after immediate place success for {}: {:?}",
                    order_id,
                    lifecycle_state
                ));
            }
        }

        // Add to pending orders and update metrics
        {
            let mut orders = self.pending_orders.write().await;
            orders.insert(order_id.clone(), pending);

            // Record metrics
            if let Some(ref metrics) = self.metrics {
                if !deferred_lifecycle {
                    metrics.record_order_placed(Self::side_to_str(side));
                }
                metrics.set_pending_orders(orders.len());
            }
        }

        debug!(
            order_id = %order_id,
            mint = %order.mint,
            side = ?side,
            price = limit_price,
            size = size,
            "Paper limit order placed"
        );

        Ok(LimitOrderEvent::OrderPlaced {
            order_id,
            mint: order.mint,
            market: order.market,
            price: limit_price,
            size,
            side,
            timestamp: order.timestamp,
            signal_id: order.signal_id,
            context: order.context,
        })
    }

    /// Cancel a pending limit order by its order ID.
    #[instrument(skip(self))]
    async fn cancel_order(&self, order_id: &str) -> Result<LimitOrderEvent> {
        let now = Utc::now();
        let deferred_lifecycle = self.config.latency_config.is_some();
        let lifecycle_state = self.lifecycle_record_cancel_request_state(order_id)?;

        let Some(lifecycle_state) = lifecycle_state else {
            debug!(
                order_id = %order_id,
                "Order not found during cancel (likely already filled or cancelled)"
            );
            return Ok(LimitOrderEvent::OrderCancelled {
                order_id: order_id.to_string(),
                reason: Some("Order already removed (filled or cancelled)".to_string()),
                timestamp: now,
            });
        };

        if matches!(lifecycle_state, LifecycleState::Terminal(_)) {
            debug!(
                order_id = %order_id,
                state = ?lifecycle_state,
                "Order already terminal during cancel request"
            );
            return Ok(LimitOrderEvent::OrderCancelled {
                order_id: order_id.to_string(),
                reason: Some("Order already removed (filled or cancelled)".to_string()),
                timestamp: now,
            });
        }

        let mut orders = self.pending_orders.write().await;
        let cancel_confirm_at = {
            let Some(pending) = orders.get_mut(order_id) else {
                debug!(
                    order_id = %order_id,
                    "Order missing from pending set during cancel request"
                );
                return Ok(LimitOrderEvent::OrderCancelled {
                    order_id: order_id.to_string(),
                    reason: Some("Order already removed (filled or cancelled)".to_string()),
                    timestamp: now,
                });
            };

            if deferred_lifecycle {
                let base_time = pending.eligible_for_fills_at.max(now);
                let candidate = self
                    .compute_cancel_confirmation_time(base_time)
                    .unwrap_or(base_time);
                let scheduled = pending
                    .cancel_confirm_at
                    .map_or(candidate, |existing| existing.min(candidate));
                pending.cancel_confirm_at = Some(scheduled);
                scheduled
            } else {
                now
            }
        };

        if deferred_lifecycle {
            debug!(
                order_id = %order_id,
                cancel_confirm_at = %cancel_confirm_at,
                "Paper cancel request accepted; awaiting lifecycle confirmation"
            );
            return Ok(LimitOrderEvent::OrderCancelled {
                order_id: order_id.to_string(),
                reason: Some("User cancelled".to_string()),
                timestamp: cancel_confirm_at,
            });
        }

        if let Some(pending) = orders.remove(order_id) {
            let _ = self.lifecycle_record_cancel_confirmed(order_id)?;
            if let Some(ref metrics) = self.metrics {
                metrics.record_order_cancelled();
                metrics.set_pending_orders(orders.len());
            }

            debug!(
                order_id = %order_id,
                remaining_size = pending.remaining_size,
                "Paper limit order cancelled"
            );
            Ok(LimitOrderEvent::OrderCancelled {
                order_id: order_id.to_string(),
                reason: Some("User cancelled".to_string()),
                timestamp: cancel_confirm_at,
            })
        } else {
            debug!(
                order_id = %order_id,
                "Order not found during cancel (likely already filled or cancelled)"
            );
            Ok(LimitOrderEvent::OrderCancelled {
                order_id: order_id.to_string(),
                reason: Some("Order already removed (filled or cancelled)".to_string()),
                timestamp: now,
            })
        }
    }

    /// Returns true - the paper trading executor supports limit orders.
    fn supports_limit_orders(&self) -> bool {
        true
    }

    /// Execute a pair redemption operation in paper trading mode.
    ///
    /// For binary markets, this simulates redeeming paired Up + Down tokens for
    /// the underlying quote currency. Each pair redeems for exactly $1.00.
    ///
    /// The paper executor simply returns a successful redemption event.
    /// The PositionManager handles the actual position and balance updates
    /// when it processes the RedemptionEvent.
    #[instrument(skip(self))]
    async fn execute_redemption(&self, action: &RedemptionAction) -> Result<RedemptionEvent> {
        debug!(
            market = %action.market,
            up_asset = %action.up_asset_id,
            down_asset = %action.down_asset_id,
            quantity = action.quantity,
            "Executing paper redemption"
        );

        // In binary markets, 1 Up + 1 Down = $1.00
        let quote_received = action.quantity;

        Ok(RedemptionEvent::RedemptionCompleted {
            market: action.market.clone(),
            up_asset_id: action.up_asset_id.clone(),
            down_asset_id: action.down_asset_id.clone(),
            quantity: action.quantity,
            quote_received,
            timestamp: action.timestamp,
        })
    }

    /// Returns true - the paper trading executor supports pair redemption.
    fn supports_redemption(&self) -> bool {
        true
    }

    /// Check for simulated fills from a Polymarket trade event.
    ///
    /// This implements the `OrderExecutor` trait method by delegating to the
    /// existing `check_fills_from_trade` method. The paper trading executor
    /// simulates order fills based on market trade events crossing pending
    /// limit order prices.
    async fn check_fills_from_trade(
        &self,
        trade: &PolymarketTradeEvent,
        inventory: &HashMap<String, f64>,
        available_quote: f64,
    ) -> Vec<LimitOrderEvent> {
        // Delegate to the existing method on self
        PaperTradingOrderExecutor::check_fills_from_trade(self, trade, inventory, available_quote)
            .await
    }

    /// Returns true - the paper trading executor simulates fills from trade events.
    fn simulates_fills(&self) -> bool {
        true
    }

    fn defers_limit_order_events(&self) -> bool {
        self.config.latency_config.is_some()
    }
